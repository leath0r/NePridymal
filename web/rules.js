// вставить блок в окно игры (и вернуть, если окно перерисовали целиком)
function rulesEnsure(sheet, id) {
  if (!sheet || !sheet.isConnected || !RULES[id] || sheet.querySelector("details.rules")) return;
  let html;
  try { html = RULES[id](); } catch (e) { return; }
  const d = document.createElement("details");
  d.className = "rules rules-auto";
  d.innerHTML = `<summary>${ic("award")}Как играть</summary><div>${html}</div>`;
  const disc = [...sheet.children].reverse().find(c => c.classList && c.classList.contains("disc"));
  disc ? sheet.insertBefore(d, disc) : sheet.appendChild(d);
  starify(d);
}
const _gameRules = ACT.game;
ACT.game = el => {
  const r = _gameRules(el), id = el.dataset.id;
  if (!RULES[id]) return r;
  const sheet = topSheet();
  [0, 300, 1200].forEach(t => setTimeout(() => rulesEnsure(topSheet() === sheet ? sheet : null, id), t));
  if (sheet && !sheet._rulesObs) {
    sheet._rulesObs = new MutationObserver(() => { if (!sheet.querySelector("details.rules")) rulesEnsure(sheet, id); });
    sheet._rulesObs.observe(sheet, { childList: true });
  }
  return r;
};
